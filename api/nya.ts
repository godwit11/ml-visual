/**
 * 学生在问「我改了什么 / 为什么变了」吗。
 *
 * ⚠️ 又是关键词表。允许的理由和 `DISTRESS` 一样：**误判代价不对称** ——
 *    多触发一次只是让她多一句"你刚把阈值拖到 0.79"，无害；
 *    漏判则会说出"我看不到你刚才动了什么"（实测真的发生过），
 *    而那恰恰是她**看得见**的东西。
 */
const ASKING_CHANGE = /(改了|改了什么|动了|调整|变化|变了|变成|怎么变|为什么变|不一样|刚才|上一步|上个问题)/

/**
 * 命中时追加到提示词**最末**的指令。
 *
 * 为什么需要它 —— 实测（2026-09-14，`nya:smoke`）：
 * 同一份提示词连问两次"我刚在页面上动了什么"，第一次答得完全正确
 * （认出是判定阈值、方向、以及召回率为什么掉），**第二次却答"我看不到"**。
 * 也就是说"上一节里有变化清单"这件事，模型有时会视而不见。
 *
 * 之后的修法有两条，缺一不可：
 *   ① 把**变化清单原样重复一遍**放进这条结尾指令里。
 *      只写"去看上面那一节"没用 —— 信息离指令太远，模型就漏了；
 *      写在指令里（近因）才真的照办。
 *   ② 给一句**可以直接照抄的开场**。要求"要提到控件和前后值"是抽象的，
 *      给例句它就能对上。
 *   （另有一条在 `handler.ts`：把 temperature 从默认 1 降到 0.3。）
 */
function changeReminder(messages: ChatMessage[], diffLines: string, mode: 'changed' | 'same' | 'none'): string {
  if (mode === 'none') return ''
  const last = [...messages].reverse().find((m) => m.role === 'user')
  if (!last || !ASKING_CHANGE.test(last.content)) return ''

  if (mode === 'same') {
    /* ⚠️ 这一支必须单列。
     *    第一版把"有快照但没变化"和"没有快照"合并进了同一个分支，
     *    于是结尾那条最高优先级的指令说成了「你手上没有可比对的上一份状态」——
     *    和上面正文直接矛盾。模型听的是结尾那条，于是答成"我看不到你之前的状态"。
     *    实测打出来的提示词是自相矛盾的，去数一遍才看出来。 */
    return `

# ⚠️ 硬性指令（优先级最高，覆盖上面所有规则）

学生正在问「我改了什么」，但你上面那份对比已经说清楚了：**他什么都没改**，
每一个数字都和上一轮一模一样。

**正确回答是「你什么都没改，数字还是上一轮那些」** ——
不要说成"我没有上一次的状态"，也不要说"我看不到"。你有，只是两边完全相同。`
  }

  return diffLines
    ? `

# ⚠️ 硬性指令（优先级最高，覆盖上面所有规则）

学生正在问「我改了什么 / 为什么这个数变了」。答案是现成的 ——
**你上一次看到的状态**和**现在**差在这些地方：

${diffLines}

你必须**照着这个说**：他动的是哪个控件、从多少变到多少、哪个指标跟着动了。
开场就照这个句式来（把内容换成上面的实际值）：
「你把**判定阈值**从 **0.50** 拖到了 **0.79**，所以**召回率**从 **0.944** 掉到了 **0.544**。」

**绝对不许回答"我看不到你刚才动了什么""我没有历史记录"** —— 你看得到，就在上面。`
    : ''
}

/* ------------------------------------------------------------------ *
 * 「别再绕了，直接回答」的硬兜底
 * ------------------------------------------------------------------ */

/**
 * 学生表达「困惑 / 不满」的信号词。
 *
 * ⚠️ 用关键词判断学生的情绪，在别处是坏做法（人的措辞无穷无尽，
 *    关键词表永远不全）。这里可以接受，因为**误判的代价是不对称的**：
 *      误判成"困惑" → 她这一轮多正面解释了一句 —— 无害
 *      漏判         → 她继续说"你拖一下看看"，学生被卡死 —— 有害
 *    所以这张表宁可放宽，宁可多触发。
 *
 * ⚠️ 但**不能**拿它当"回答质量"的判据（`nya-smoke.mjs` 里已经踩过这个坑：
 *    用子串判大模型的输出会产生假失败）。这里判的是**学生**的输入，
 *    而学生的短消息恰好是收敛的 —— 这两件事的性质不同。
 */
const DISTRESS =
  /(不懂|没懂|不明白|什么意思|啥意思|啊哈|啊\?|啊？|哈\?|困惑|迷茫|看不懂|不理解|只会说|就这|别卖关子|说人话|你就直说|直说吧|废话|老是这|又来了|离谱|晕)/

/** 去掉标点和空白，用于判断"同一个问题是不是又问了一遍" */
function normalize(text: string): string {
  return text.replace(/[\s，。？！?!、,.~～]/g, '')
}

/**
 * 从最新往回数：连续多少条**助教回复**里带问号。
 *
 * 跳过学生消息 —— 我们数的是"她连着反问了几轮"。
 * 碰到第一条不带问号的助教回复就停：说明她已经正面回答过，计数该归零。
 *
 * ⚠️ 这个判据**不够**：实测那次卡住的对话里，她第二条回答是
 *    「点一下…左右拖动它」（命令句、没有问号），光数问号会漏判。
 *    所以它只是三个触发条件之一，主判据在学生那一侧。
 */
function consecutiveQuestionReplies(messages: ChatMessage[]): number {
  let n = 0
  for (let i = messages.length - 1; i >= 0; i--) {
    const m = messages[i]
    if (m.role !== 'assistant') continue
    if (/[?？]/.test(m.content)) n++
    else break
  }
  return n
}

/**
 * 该不该强制她这一轮正面回答。
 *
 * 三个触发条件，命中任一即可（宁多勿漏）：
 *   ① 学生明说困惑或抗议  ← 主判据，覆盖实测那次卡死的场景
 *   ② 她连着两轮都在反问
 *   ③ 学生把同一个问题又问了一遍
 */
function shouldAnswerDirectly(messages: ChatMessage[]): boolean {
  const userMsgs = messages.filter((m) => m.role === 'user')
  const last = userMsgs[userMsgs.length - 1]
  if (!last) return false

  if (DISTRESS.test(last.content)) return true
  if (consecutiveQuestionReplies(messages) >= 2) return true

  const key = normalize(last.content)
  if (key.length >= 4 && userMsgs.slice(0, -1).some((m) => normalize(m.content) === key)) return true

  return false
}

/**
 * 该强制正面回答时，返回一段**必须照办**的指令；否则返回空串。
 *
 * ⚠️ 改这段之前先读上面调用处的注释 —— 它存在的原因是
 *    「模型自己数自己会数错」，不是因为我们喜欢写长提示词。
 */
function escalationNotice(messages: ChatMessage[]): string {
  if (!shouldAnswerDirectly(messages)) return ''

  return `

# ⚠️ 硬性指令（优先级最高，覆盖上面所有规则）

学生这一轮在表达困惑、不满，或者你前面连着两轮都只是让他"自己看看"。
不论哪种情况，**这一轮禁止反问，也禁止再让他"拖一下看看"**。必须做到：

1. **直接给出正面解释**。用三到四句话，把学生问的那个东西讲清楚：
   该给定义就给定义，该给数字就给数字，该举例子就举例子。
2. 如果学生明确表达过困惑或不满（比如「啊哈？」「你怎么只会说这一句」），
   **先用半句话认下来**（例如「是我绕远了」），再解释 —— 不要装作没看见。
3. 这一轮的回答里**不允许出现问号**，也不允许出现「你试试」「你去拖一下」这类指令。`
}

/**
 * 把前端上报的状态格式化成提示词里的一行行文本。
 *
 * 只有白名单里的键会被采用；值一律转成字符串并截断长度，
 * 防止有人塞一段超长文本进来干扰提示词。
 */
function formatState(demo: DemoKnowledge, state: Record<string, unknown> | undefined): string {
  const lines = pickState(demo, state)
  return lines.map(([k, v]) => `- ${k} = ${v}`).join('\n')
}

/** 白名单过滤 + 转字符串 + 截断。返回 [键, 值] 列表 */
function pickState(
  demo: DemoKnowledge,
  state: Record<string, unknown> | undefined,
): [string, string][] {
  if (!state) return []
  const out: [string, string][] = []
  for (const key of demo.stateKeys) {
    if (!(key in state)) continue
    const raw = state[key]
    if (raw === null || raw === undefined) continue
    const text = String(raw).trim()
    if (!text || text === '-') continue
    out.push([key, text.slice(0, MAX_STATE_VALUE)])
  }
  return out
}

/**
 * 和上次相比变了什么。
 *
 * ⚠️ 只在**同一页**的两份快照之间比。两页的键不一样，硬比会把
 *    「数据集」这种同名不同义的键也算成"变了"。
 * ⚠️ 变了多少**不由我算**（不做减法）—— 只把前后两个值并排放着，
 *    让模型自己算。数字算错了比不给更糟，而它算出减法比我们可靠。
 */
function formatDiff(
  demo: DemoKnowledge,
  prev: Record<string, unknown> | undefined,
  state: Record<string, unknown> | undefined,
): string {
  if (!prev || !state) return ''
  const now = new Map(pickState(demo, state))
  const rows: string[] = []
  for (const [key, before] of pickState(demo, prev)) {
    const after = now.get(key)
    if (after === undefined || after === before) continue
    rows.push(`- ${key}：${before} → ${after}`)
    if (rows.length >= MAX_DIFF_ROWS) break
  }
  return rows.join('\n')
}

