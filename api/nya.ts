/**
 * Nya · 机器学习入门助教
 *
 * 这个文件只做两件事：定义 Nya 是谁、以及把她"当前能看到什么"组装成提示词。
 * 不碰网络、不碰 HTTP —— 那些在 `handler.ts` 里，便于分别测试。
 *
 * ------------------------------------------------------------------ *
 * 设计上的三个关键决定（都不是随手定的）
 * ------------------------------------------------------------------ *
 *
 * 1. **知识放在服务端，不信任前端。**
 *    前端只允许上报一组**白名单里的状态键**（如当前斜率是几）。
 *    关于「这一页讲什么」「有哪些术语」这类内容，全部由服务端查表给出。
 *    原因：如果让前端随便塞一段"事实"进提示词，就等于把系统提示词
 *    的控制权交给了浏览器 —— 那是提示词注入的入口。
 *    这里虽然只是个教学助手、没有敏感操作，但结构上一开始就该是干净的。
 *
 * 2. **用真实数字防幻觉。**
 *    站点的立站原则是「页面上每个数字都要能追溯到某次真实运行」。
 *    如果 Nya 随口说一个和页面冲突的数字，就违背了站点自己的价值观。
 *    所以把页面的真实状态当"唯一可靠事实来源"写进提示词，
 *    并明确禁止她在这些数字之外编造。
 *
 * 3. **反问优先。**
 *    直接给答案会让初学者产生依赖，不再自己观察那条直线。
 *    所以设定成：先反问一句把学生推向观察，只有在他明确说"还是不懂"时才正面回答。
 *    （这条是用户明确认可的教学策略，不要改成"有问必答"。）
 */

/** 一页的「服务端知识」——前端无法伪造 */
export interface DemoKnowledge {
  id: string
  title: string
  /** 这一页解决什么问题。用生活语言写，不出现术语 */
  what: string
  /** 页面上会出现的术语，每个配一句人话 */
  terms: { name: string; say: string }[]
  /** 关于这页的硬事实：不随用户调参变化，且已经在页面上验证过 */
  facts: string[]
  /**
   * 这一页有哪几张图、分别画什么。
   *
   * 🔴 存在的理由（2026-09-16）：Nya **看不到任何图形**，但她知道每一页在讲什么，
   *    于是她会**描述外观** —— 而图是跟着参数实时重画的，她描述的往往不是真的。
   *    实测：学生问「S 形曲线在哪」，她答「主图背景里那条 S 形曲线」——
   *    主图背景是一片概率色块、根本没有曲线，真正的曲线在下方右边那张小图里；
   *    她还编了个「虚线是概率 0.1 和 0.9 的边界」（页面上没有这种线）。
   *
   *    ⇒ 有了这份清单，她可以答**位置和名字**（学生能核对）；
   *      而 header 里那条「看不到图形」的约束禁止她答**外观**。
   */
  charts?: { title: string; what: string }[]
  /**
   * 允许前端上报的状态键白名单。
   * 不在这个列表里的键会被丢弃 —— 这是防提示词注入的第一道闸。
   */
  stateKeys: string[]
}

